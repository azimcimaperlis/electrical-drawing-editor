/* Build the shared symbol library (library/simbol.js) loaded by every user.
 *   node tools/build_library.js                      -> keep current library
 *   node tools/build_library.js pustaka-simbol.json  -> merge symbols exported from the editor ("Eksport pustaka")
 *   node tools/build_library.js --drawing drawings/qlwb.json  -> capture symbols from a converted drawing
 * Duplicates (same shape in any rotation/mirror) are skipped. */
const fs = require('fs');
const path = require('path');
const C = require('../js/capture.js');
const OUT = path.join(__dirname, '..', 'library', 'simbol.js');

let lib = { version: 1, symbols: [] };
if (fs.existsSync(OUT)) {
  const src = fs.readFileSync(OUT, 'utf8');
  lib = JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1));
}
const known = new Set(lib.symbols.map(s => C.signature(s.ents)));
let added = 0;
const add = (s, src) => {
  const sig = C.signature(s.ents);
  if (known.has(sig)) return;
  known.add(sig);
  lib.symbols.push({ id: 'sh' + (lib.symbols.length + 1), name: s.name, cat: s.cat || 'Lain-lain', ents: s.ents, src: s.src || src || '' });
  added++;
};
const args = process.argv.slice(2);
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--drawing') {
    const d = JSON.parse(fs.readFileSync(args[++i], 'utf8'));
    for (const s of C.detect(d)) if (s.cat !== 'Lain-lain') add(s, d.name);
  } else {
    const o = JSON.parse(fs.readFileSync(args[i], 'utf8'));
    for (const s of (Array.isArray(o) ? o : o.symbols || [])) if (s && Array.isArray(s.ents)) add(s);
  }
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, '/* Shared symbol library - generated by tools/build_library.js */\nwindow.SHARED_SYMBOLS = ' + JSON.stringify(lib) + ';\n');
console.log(OUT, lib.symbols.length + ' symbols (' + added + ' added)');
